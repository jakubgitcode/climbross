const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const output = path.resolve(process.env.HOME, 'climbross-test-results');
fs.mkdirSync(output, { recursive: true });
const server = http.createServer((req, res) => {
  const url = new URL(req.url, 'http://localhost');
  if (!url.pathname.startsWith('/climbross/')) { res.writeHead(404).end(); return; }
  const file = path.resolve(root, '.' + url.pathname.slice('/climbross'.length) + (url.pathname.endsWith('/') ? 'index.html' : ''));
  if (!file.startsWith(root + '/')) { res.writeHead(403).end(); return; }
  const mime = { '.js': 'text/javascript', '.css': 'text/css', '.html': 'text/html', '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml' };
  try { res.setHeader('Content-Type', mime[path.extname(file)] || 'text/plain'); res.end(fs.readFileSync(file)); }
  catch { res.writeHead(404).end(); }
});
(async () => {
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  let browser;
  try {
    browser = await chromium.launch({ executablePath: '/snap/bin/chromium', headless: true });
    const context = await browser.newContext({ viewport: { width: 393, height: 851 }, colorScheme: 'dark', reducedMotion: 'reduce' });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', e => console.error('BROWSER ERROR', e.message));
    page.on('pageerror', (e) => errors.push(e.message));
    const url = `http://127.0.0.1:${server.address().port}/climbross/`;
    const ready = () => page.waitForFunction(() => document.documentElement.dataset.ready === '1');
    await page.goto(url); await ready();
    await page.locator('[data-view="training"]').click();
    assert.match(await page.locator('#planPreview').innerText(), /Najpierw zapisz maksimum/);
    await page.locator('[data-view="profile"]').click();
    await page.locator('[name="maxLeftKg"]').fill('50');
    await page.locator('[name="maxRightKg"]').fill('80');
    await page.locator('#profileForm button[type="submit"]').click();
    await page.locator('[data-view="training"]').click();
    await page.locator('#trainingForm [name="hand"]').selectOption('left');
    assert.match(await page.locator('#planPreview').innerText(), /cel 10.0 kg/);
    await page.locator('#trainingStart').click();
    assert.equal(await page.locator('#coachLive').isVisible(), false);
    console.log('PASS percent preview and connection guard');
    await page.locator('[data-preset="flight"]').click();
    await page.locator('#trainingForm [name="unit"]').selectOption('kg');
    await page.locator('#trainingForm [name="target"]').fill('38');
    for (const [field, value] of Object.entries({ workS: '2', restS: '1', reps: '2', sets: '1', name: 'Test flight' })) await page.locator(`#trainingForm [name="${field}"]`).fill(value);
    await page.locator('#planSave').click();
    await page.waitForFunction(() => [...document.querySelector('#savedPlans').options].some(o => o.text === 'Test flight'));
    await page.evaluate(() => scrollTo(0, 0));
    await page.screenshot({ path: path.join(output, 'training-settings.png'), fullPage: true });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    await page.locator('[data-view="profile"]').click();
    await page.locator('#demoBtn').click();
    await page.locator('[data-view="training"]').click();
    await page.locator('#trainingStart').click();
    assert.equal(await page.locator('#trainingFields').evaluate(el => el.disabled), true);
    assert.equal(await page.locator('#startBtn').isDisabled(), true);
    assert.equal(await page.locator('#tareBtn').isDisabled(), true);
    await page.waitForFunction(() => document.querySelector('#coachPhase').textContent.startsWith('Praca'), { timeout: 10000 });
    await page.locator('#coachLive').scrollIntoViewIfNeeded();
    await page.screenshot({ path: path.join(output, 'flight.png') });
    await page.waitForFunction(() => !document.querySelector('#coachResult').hidden, { timeout: 15000 });
    assert.match(await page.locator('#coachResultTitle').innerText(), /Ukończono.*DEMO/);
    assert.match(await page.locator('#coachResultText').innerText(), /2\/2 powtórzeń/);
    await page.locator('#coachSave').click();
    await page.waitForFunction(() => document.querySelector('#coachResult').hidden);
    await page.locator('[data-view="history"]').click();
    await page.waitForFunction(() => document.querySelectorAll('#histList .item').length === 1);
    await page.locator('.item-main').click();
    assert.match(await page.locator('.item-detail').innerText(), /cel 38.0 kg/);
    assert.equal(await page.locator('.best.left .v').innerText(), '–');
    const backup = await page.evaluate(async () => (await import('./js/store.js')).exportAll());
    assert.equal(backup.measurements[0].training.completed, true);
    assert.equal(backup.profile.maxLeftKg, 50);
    assert.equal(backup.trainingPlans[0].name, 'Test flight');
    assert.equal(backup.trainingPlans[0].hand, 'left');
    console.log('PASS flight, completion, saved history, demo isolation and unchanged max');
    await page.evaluate(async () => { const s = await import('./js/store.js'); for (const m of await s.listMeasurements()) await s.deleteMeasurement(m.id); await s.saveTrainingPlans([]); });
    await page.reload(); await ready();
    await page.locator('[data-view="profile"]').click();
    await page.locator('#importInput').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
    await page.waitForFunction(() => document.querySelector('#toast').textContent.startsWith('Imported'));
    await page.locator('[data-view="training"]').click();
    await page.locator('#savedPlans').selectOption('0');
    assert.equal(await page.locator('#trainingForm [name="name"]').inputValue(), 'Test flight');
    assert.equal(await page.locator('#trainingForm [name="hand"]').inputValue(), 'left');
    const imported = await page.evaluate(async () => (await import('./js/store.js')).exportAll());
    assert.deepEqual(imported.measurements, backup.measurements);
    console.log('PASS reload persistence and export/import of plans and sessions');
    await page.locator('[data-view="profile"]').click(); await page.locator('#demoBtn').click();
    await page.locator('[data-view="training"]').click(); await page.locator('#trainingStart').click();
    await page.locator('#connectBtn').click();
    assert.match(await page.locator('#coachResultTitle').innerText(), /rozłączono/);
    assert.equal(await page.locator('#startBtn').isDisabled(), true);
    await page.locator('#coachDiscard').click();
    console.log('PASS disconnect interruption and result discard');
    await page.locator('[data-view="profile"]').click(); await page.locator('#demoBtn').click();
    await page.locator('[data-view="training"]').click();
    await page.locator('[data-preset="endurance"]').click();
    await page.locator('#trainingStart').click();
    assert.equal(await page.locator('#flight').isVisible(), false);
    assert.match(await page.locator('#coachTarget').innerText(), /Cel 10.0 kg/);
    await page.locator('#trainingStop').click();
    assert.match(await page.locator('#coachResultTitle').innerText(), /Zatrzymano ręcznie/);
    await page.locator('[data-view="measure"]').click();
    await page.locator('#startBtn').click();
    assert.equal(await page.locator('#startBtn').innerText(), 'Start');
    await page.locator('[data-view="training"]').click(); await page.locator('#coachDiscard').click();
    console.log('PASS percentage training, manual stop and unsaved result guard');
    await page.evaluate(async () => { await navigator.serviceWorker.ready; });
    await page.waitForFunction(() => !!navigator.serviceWorker.controller);
    await context.setOffline(true);
    await page.reload(); await ready();
    await page.locator('[data-view="training"]').click();
    assert.equal(await page.locator('#trainingStart').isVisible(), true);
    await page.locator('#savedPlans').selectOption('0');
    assert.equal(await page.locator('#trainingForm [name="target"]').inputValue(), '38');
    console.log('PASS offline shell at GitHub Pages subpath');
    assert.deepEqual(errors, []);
    console.log('PASS no browser JavaScript errors');
  } finally { if (browser) await browser.close(); server.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
